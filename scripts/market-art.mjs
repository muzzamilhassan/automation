// market-files P1.5 — the ART FETCHER (docs/qa/market-files-p1.5-qa.md):
//   node scripts/market-art.mjs [--fresh]
// Downloads the curated cartoon cast + props from the committed DATA
// manifest (explainer/public/assets/market/manifest.json) into the same
// folder. Idempotent: files already on disk are skipped, so CI re-runs are
// cheap. Every asset is free-license (CC0); CREDITS.md is regenerated from
// the manifest on each run. Loud failures: a bad download stops the run.
import fs from 'node:fs';
import path from 'node:path';

const ART_DIR = path.resolve('explainer', 'public', 'assets', 'market');
const manifestPath = path.join(ART_DIR, 'manifest.json');
if (!fs.existsSync(manifestPath)) { console.error('manifest missing — explainer/public/assets/market/manifest.json'); process.exit(1); }
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const fresh = process.argv.includes('--fresh');

async function grab(item, dir) {
  const dest = path.join(dir, item.file);
  if (!fresh && fs.existsSync(dest) && fs.statSync(dest).size > 1024) return 'cached';
  const res = await fetch(item.url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${item.url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 1024) throw new Error(`suspiciously small (${buf.length}B) ${item.url}`);
  const head = buf.subarray(0, 64).toString('utf8');
  if (dest.endsWith('.svg') && !/<svg|<\?xml/.test(head)) throw new Error(`not an SVG: ${item.url}`);
  if (dest.endsWith('.png') && !buf.subarray(0, 4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47]))) throw new Error(`not a PNG: ${item.url}`);
  fs.writeFileSync(dest, buf);
  return `${item.file} ${(buf.length / 1024).toFixed(0)}KB`;
}

for (const [group, dirName] of [['peeps', 'peeps'], ['icons', 'icons'], ['lottie', 'lottie'], ['scenes', 'scenes']]) {
  const dir = path.join(ART_DIR, dirName);
  fs.mkdirSync(dir, { recursive: true });
  const items = manifest[group] || [];
  let got = 0, skipped = 0;
  for (const item of items) {
    try {
      const r = await grab(item, dir);
      if (r === 'cached') skipped++; else { console.log(`[art] ${group}/${r}`); got++; }
    } catch (e) { console.error(`[art] ✗ ${group}/${item.file}: ${e.message}`); process.exit(1); }
  }
  console.log(`[art] ${group}: ${got} downloaded, ${skipped} cached`);
}

// CREDITS — regenerated from the manifest (R2). CC0 items need no
// attribution; recorded so the origin of every file stays answerable.
const credits = `# Market art credits (regenerated by scripts/market-art.mjs)

- Peeps: ${manifest.peeps.length} characters from ${manifest.sources.peeps}
  — CC0 (public domain): free for commercial use, no attribution required.
  Source URLs are in manifest.json next to each file.
- Icons: ${manifest.icons.length} 3D props from ${manifest.sources.icons}
  — CC0-1.0: free for commercial use, no attribution required.
- Scenes: ${manifest.scenes.length} full-scene illustrations from
  ${manifest.sources.storyset} — free license WITH attribution: every
  video using them MUST carry the line "Illustrations by Storyset /
  Freepik" in its description.
- Lottie accents: authored in-repo unless a manifest entry says otherwise
  (any community .json added here MUST get a license note in manifest.json).
`;
fs.writeFileSync(path.join(ART_DIR, 'CREDITS.md'), credits);
console.log('[art] ✅ CREDITS.md written — art ready');
